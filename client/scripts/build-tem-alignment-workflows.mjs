// One approved MCP call per child skill. Algorithms live in autoalign.py.
import { mkdir, writeFile, readFile, unlink } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { stringify } from 'yaml'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../skills')
const phases = [
  ['beamAlignment', 'beam-alignment', 'beam', 'align_beam_and_c2', 'Beam shift and C2 aperture', 'spot <0.02; spread <0.01 when C2 is inserted'],
  ['gun', 'gun-tilt-alignment', 'gun', 'align_gun_tilt', 'Gun tilt', 'no probe current gain >=0.5%'],
  ['condenser', 'condenser-stigmation', 'c2stig', 'align_condenser_stigmation', 'Condenser astigmatism', 'ellipticity <0.03'],
  ['zAlignment', 'eucentric-alignment', 'z', 'align_eucentric_z', 'Eucentric stage Z', 'residual Z correction <100 nm'],
  ['rotation', 'rotation-center-alignment', 'rot', 'align_rotation_center', 'Rotation centre', 'beam-tilt offset <0.8 mrad'],
  ['objective', 'objective-stigmation', 'ostig', 'align_objective_stigmation', 'Objective astigmatism', 'Thon-ring astigmatism <3 nm'],
]

export const builders = Object.fromEntries(phases.map(([key, folder, phase, tool, title, tolerance]) => [key, () => ({
  folder: `tem-twin-phase-${phase}`,
  finish: () => ({
    schema_version: 1, id: `tem_twin_phase_${phase}`, version: '5.0.0',
    steps: [{
      id: `${phase}_align`, title,
      purpose: `Run the original autoalign.py ${phase} algorithm and verify ${tolerance}.`,
      tool: `agent_mcp_tem_twin.${tool}`, parameters: { device: { mode: 'result', value: '{{select_device.device}}' } },
      confirm: false, confirmation: '',
      expected_output: `Structured correction and verification evidence, verified=true only when ${tolerance} and working conditions were restored. Preserve execution-result review.`,
      completion: { type: 'field_equals', field: 'verified', value: true },
      on_success: 'complete', on_failure: 'pause', on_error: 'pause', max_visits: 1,
    }],
  }),
})]))

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const selectorDir = resolve(root, 'tem-tango-device-selection')
  await mkdir(resolve(selectorDir, 'references'), { recursive: true })
  await writeFile(resolve(selectorDir, 'SKILL.md'), `---
name: tem-tango-device-selection
description: "Ask the user to choose the Tango target before any TEM calibration. Shared first phase of TEM workflows."
metadata:
  display_name: Select TEM Device
  edmore: {authority: workflow, workflow: references/workflow.yaml}
---

Ask the user which registered Tango device to operate. Do not infer consent from
there being only one device, and never silently default to a Twin or real hardware.
The registered MCP device enums and list_devices describe the available targets;
list_devices is discovery, not permission to operate. The user must explicitly
choose the exact target before select_device executes. Preserve the ask gate.
This read-only step validates the connection and returns device for result binding.
It changes no global target. All later phase tools bind this same result.
Do not automatically replay a completed selection to switch targets in an active
workflow; changing target requires a new plan and confirmation.
`)
  await writeFile(resolve(selectorDir, 'references/workflow.yaml'), stringify({
    schema_version: 1, id: 'tem_tango_device_selection', version: '1.0.0', steps: [{
      id: 'select_device', title: 'Choose the TEM device', purpose: 'Ask the user which registered device to use before instrument operations.',
      tool: 'agent_mcp_tem_twin.select_device', parameters: { device: { mode: 'ask' } },
      confirm: true, confirmation: 'Which registered Tango device should this workflow control? Confirm its exact device name.',
      expected_output: 'The explicitly chosen device identity, kind and available=true. No instrument mutation.',
      completion: { type: 'field_equals', field: 'available', value: true },
      on_success: 'complete', on_failure: 'pause', on_error: 'pause', max_visits: 1,
    }],
  }))
  for (const [index, build] of Object.values(builders).entries()) {
    const graph = build()
    const [, folder, phase, , title] = phases[index]
    const path = resolve(root, graph.folder, 'references/workflow.yaml')
    await mkdir(dirname(path), { recursive: true })
    await writeFile(path, '# Generated by scripts/build-tem-alignment-workflows.mjs.\n' + stringify(graph.finish()))
    const wrapperDir = resolve(root, `tem-twin-${folder}`)
    const original = await readFile(resolve(wrapperDir, 'SKILL.md'), 'utf8')
    const body = original.replace(/^---\n[\s\S]*?\n---\n/, '').replace('Run the single tool declared in [workflow.yaml](references/workflow.yaml).', 'First ask the user to choose the target via tem-tango-device-selection, then run the one calibration phase declared in manifest.json.')
    await writeFile(resolve(root, graph.folder, 'SKILL.md'), `---
name: ${graph.folder}
description: "Internal ${title} phase. Requires select_device evidence from the same workflow; use the public selection-plus-calibration workflow for standalone requests."
metadata:
  display_name: ${title} Phase
  edmore: {authority: workflow, workflow: references/workflow.yaml}
---

Run only as part of a workflow containing tem-tango-device-selection first.
Bind device to {{select_device.device}}; never replace a missing result with a
default. Keep verified=true, restoration evidence and execution-result review.
${body.replace('First ask the user to choose the target via tem-tango-device-selection, then run the one calibration phase declared in manifest.json.', 'Run the single tool declared in references/workflow.yaml.').trim()}
`)
    await writeFile(resolve(wrapperDir, 'SKILL.md'), `---
name: tem-twin-${folder}
description: "ONLY ${title}: ask which Tango device to use, then run this single bounded calibration. For overall alignment use tem-twin-alignment-sequence."
metadata:
  display_name: TEM ${title}
  edmore: {authority: workflow}
  kind: compound_workflow
---
${body}`)
    await writeFile(resolve(wrapperDir, 'manifest.json'), JSON.stringify({
      id: `tem_twin_${folder.replaceAll('-', '_')}`, name: `TEM ${title}`, version: '5.0.0',
      description: `Choose the target, then perform ONLY ${title}.`, kind: 'compound_workflow',
      agents: ['agent_mcp_tem_twin'], required_tools: [], ordered_tools: [],
      references: ['tem_tango_device_selection', `tem_twin_phase_${phase}`],
    }, null, 2) + '\n')
    await unlink(resolve(wrapperDir, 'references/workflow.yaml')).catch(error => { if (error.code !== 'ENOENT') throw error })
    console.log(`${graph.folder}: 1 phase; public wrapper: selection + phase`)
  }
}
